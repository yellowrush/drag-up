function yarnTile(id, x, y, z, kind, extra) {
  var node = Object.assign({
    id: id,
    label: id,
    x: x,
    y: y,
    z: z || 0,
    kind: kind || 'safe',
  }, extra || {});
  if (
    node.stable == null &&
    (node.kind === 'safe' || node.kind === 'start' || node.kind === 'goal' || node.kind === 'switch' || node.kind === 'stair')
  ) {
    node.stable = true;
  }
  return node;
}

